/** Maps a KR8_* / client error code to the English key of a friendly message (translated by L()). */
/** Fetches one language's V5 strings (zh, hi, ja, ko live in their own small files). Resolves at once for en / th or when loaded. */
const V5_LOADERS: Record<string, () => Promise<{ default: Record<string, string> }>> = {
  zh: () => import('./strings/v5.zh'),
  hi: () => import('./strings/v5.hi'),
  ja: () => import('./strings/v5.ja'),
  ko: () => import('./strings/v5.ko'),
};
const v5Loading: Record<string, Promise<void>> = {};
export function v5LangReady(lang: string): boolean {
  return !V5_LOADERS[lang] || !!V5_L[lang];
}
export function loadV5Lang(lang: string): Promise<void> {
  if (v5LangReady(lang)) return Promise.resolve();
  if (!v5Loading[lang]) {
    v5Loading[lang] = V5_LOADERS[lang]()
      .then((m) => { V5_L[lang] = m.default; })
      .catch(() => { delete v5Loading[lang]; });
  }
  return v5Loading[lang];
}

